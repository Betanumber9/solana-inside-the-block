"""Pre-registered tests P11 and P12 (PREREGISTRATION.md, addendum 3): independent probes on the direct path, by class."""
import collections
import json
import pathlib
import random

from .analyze import boot_ci, fmt, load_jsonl


def main(cfg, a):
    data = pathlib.Path(cfg.data_dir)
    rng = random.Random(19)
    g = collections.defaultdict(lambda: collections.defaultdict(lambda: [0, 0]))
    for run in a.runs.split(","):
        d = data / "runs" / run
        cls = {pk: ("front_end" if t["tpu_elsewhere"] else "own_tpu")
               for pk, t in json.loads((d / "meta.json").read_text())["targets"].items()}
        landed = {r["sig"]: r for r in load_jsonl(d / "landed.jsonl") if r.get("index") is not None}
        blocks = collections.defaultdict(list)
        for s in load_jsonl(d / "sends.jsonl"):
            x = landed.get(s["sig"])
            if x and x["in_window"] and s.get("path") == "tpu" and s["series"] == "ladder_indep":
                blocks[(s["burst"], x["landed_slot"])].append(dict(s, index=x["index"]))
        for (burst, slot), lst in blocks.items():
            for i in range(len(lst)):
                for j in range(i + 1, len(lst)):
                    x, y = lst[i], lst[j]
                    first = x if x["index"] < y["index"] else y
                    for key in (cls[x["leader"]], x["client"]):
                        c = g[key][(run, burst)]
                        c[0] += first["price"] == max(x["price"], y["price"])
                        c[1] += 1
    res = {k: boot_ci(list(v.values()), rng) for k, v in g.items()}
    L = ["# Independent probes, direct path: pre-registered tests P11, P12 (generated by `python -m itb indep`)", "",
         "Runs: " + a.runs, "", "| test | group | higher fee first [95% CI] | bursts | holds |", "|---|---|---|---|---|"]
    for name, k in (("P11", "front_end"), ("P12", "own_tpu")):
        v = res.get(k)
        holds = "-" if not v or v[0] is None else ("yes" if v[1] > 0.5 else "**no**")
        L.append("| %s | %s | %s | %d | %s |" % (name, k, fmt(v), len(g[k]), holds))
    L += ["", "| client | higher fee first [95% CI] | bursts |", "|---|---|---|"]
    for k in sorted(res):
        if k not in ("front_end", "own_tpu"):
            L.append("| %s | %s | %d |" % (k, fmt(res[k]), len(g[k])))
    out = pathlib.Path("reports") / "indep"
    out.mkdir(parents=True, exist_ok=True)
    (out / "summary.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L))
