"""Pre-registered path comparison (PREREGISTRATION.md, addendum of 4 November): RPC against direct TPU.
Uses runs whose sends carry path = "tpu" for some bursts; the test run of 4 November is excluded by default."""
import collections
import json
import pathlib
import random

from .analyze import boot_ci, fmt, load_jsonl

TEST_RUN = "20261104T062417Z_live"


def share(groups):
    return sum(h for h, n in groups) / max(1, sum(n for h, n in groups))


def diff_ci(a1, a0, rng):
    if not a1 or not a0:
        return None
    stats = sorted(share([a1[rng.randrange(len(a1))] for _ in a1]) - share([a0[rng.randrange(len(a0))] for _ in a0])
                   for _ in range(2000))
    return share(a1) - share(a0), stats[50], stats[1949]


def main(cfg, a):
    data = pathlib.Path(cfg.data_dir)
    rng = random.Random(13)
    sends, landed, cls = [], {}, {}
    for d in sorted((data / "runs").glob("*_live")):
        if (a.runs and d.name not in a.runs.split(",")) or (not a.runs and d.name == TEST_RUN):
            continue
        rows = load_jsonl(d / "sends.jsonl")
        if not any(r.get("path") == "tpu" for r in rows):
            continue
        for pk, t in json.loads((d / "meta.json").read_text())["targets"].items():
            cls[pk] = "front_end" if t["tpu_elsewhere"] else "own_tpu"
        sends += rows
        for r in load_jsonl(d / "landed.jsonl"):
            if r.get("index") is not None:
                landed[r["sig"]] = r
    if not sends:
        raise SystemExit("no path runs found")
    land = collections.defaultdict(collections.Counter)
    blocks = collections.defaultdict(list)
    for s in sends:
        x = landed.get(s["sig"])
        c = cls[s["leader"]]
        if not x:
            land[(c, s["path"])]["lost"] += 1
            continue
        land[(c, s["path"])]["in_window" if x["in_window"] else "outside"] += 1
        land[(c, s["path"])]["off%+d" % min(x["slot_offset"], 9)] += 1
        if x["in_window"]:
            blocks[(s["run"], s["burst"], x["landed_slot"])].append(dict(s, index=x["index"]))
    g = collections.defaultdict(lambda: collections.defaultdict(lambda: [0, 0]))
    for (run, burst, slot), lst in blocks.items():
        for i in range(len(lst)):
            for j in range(i + 1, len(lst)):
                x, y = lst[i], lst[j]
                first, second = (x, y) if x["index"] < y["index"] else (y, x)
                near = abs(x["index"] - y["index"]) <= 15
                for c in (cls[x["leader"]], x["client"]):
                    key = (c, x["path"])
                    cnt = g[key + ("sent_first",)][(run, burst)]
                    cnt[0] += first["send_pos"] < second["send_pos"]
                    cnt[1] += 1
                    if x["price"] != y["price"]:
                        for kind in ("fee_first",) + (("fee_first_near",) if near else ()):
                            cnt = g[key + (kind,)][(run, burst)]
                            cnt[0] += first["price"] > second["price"]
                            cnt[1] += 1
    val = lambda c, p, k: list(g[(c, p, k)].values())
    p7 = diff_ci(val("own_tpu", "tpu", "sent_first"), val("own_tpu", "rpc", "sent_first"), rng)
    p8 = diff_ci(val("front_end", "tpu", "fee_first_near"), val("front_end", "rpc", "fee_first_near"), rng)
    f = lambda v: "no data" if v is None else "%+.2f [%+.2f, %+.2f]" % v
    L = ["# Path comparison: pre-registered tests (generated by `python -m itb paths`)", "",
         "Runs: " + ", ".join(sorted({s["run"] for s in sends})), "",
         "| test | what | tpu minus rpc [95% CI] | prediction holds |", "|---|---|---|---|",
         "| P7 | own_tpu: sent_first | %s | %s |" % (f(p7), "-" if p7 is None else ("yes" if p7[0] >= 0 else "**no**")),
         "| P8 | front_end: fee_first, pairs <=15 apart | %s | %s |" % (
             f(p8), "-" if p8 is None else ("yes" if p8[1] <= 0 <= p8[2] else "**no**")),
         "", "## Shares by path", "", "| group | path | measure | share [95% CI] |", "|---|---|---|---|"]
    for k in sorted(g):
        L.append("| %s | %s | %s | %s |" % (k[0], k[1], k[2], fmt(boot_ci(list(g[k].values()), rng))))
    L += ["", "## Landing by path (probes)", "", "| group | path | in window | outside | lost | slot offsets |",
          "|---|---|---|---|---|---|"]
    for (c, p), cnt in sorted(land.items()):
        offs = " ".join("%s:%d" % (k[3:], v) for k, v in sorted(cnt.items(), key=lambda kv: int(kv[0][3:]) if
                                                                kv[0].startswith("off") else 99) if k.startswith("off"))
        L.append("| %s | %s | %d | %d | %d | %s |" % (c, p, cnt["in_window"], cnt["outside"], cnt["lost"], offs))
    out = pathlib.Path("reports") / "paths"
    out.mkdir(parents=True, exist_ok=True)
    (out / "summary.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L))
