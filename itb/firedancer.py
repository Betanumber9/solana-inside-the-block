"""Pre-registered tests P9 and P10 (PREREGISTRATION.md, addendum 2): the two Firedancer nodes, direct path only."""
import collections
import pathlib
import random

from .analyze import boot_ci, fmt, load_jsonl

JD549 = "JD549HsbJHeEKKUrKgg4Fj2iyv2RGjsV7NTZjZUrHybB"
NINE = "9eGrDohdNTAo61DRHyfMuqKWXqYnA3i254Wiszxe8FoY"


def main(cfg, a):
    data = pathlib.Path(cfg.data_dir)
    rng = random.Random(17)
    blocks = collections.defaultdict(list)
    for run in a.runs.split(","):
        d = data / "runs" / run
        landed = {r["sig"]: r for r in load_jsonl(d / "landed.jsonl") if r.get("index") is not None}
        for s in load_jsonl(d / "sends.jsonl"):
            x = landed.get(s["sig"])
            if x and x["in_window"] and s.get("path") == "tpu" and s["leader"] in (JD549, NINE):
                blocks[(run, s["burst"], x["landed_slot"])].append(dict(s, index=x["index"]))
    g = collections.defaultdict(lambda: collections.defaultdict(lambda: [0, 0]))
    for (run, burst, slot), lst in blocks.items():
        for i in range(len(lst)):
            for j in range(i + 1, len(lst)):
                x, y = lst[i], lst[j]
                if x["price"] == y["price"]:
                    continue
                first = x if x["index"] < y["index"] else y
                c = g[x["leader"]][(run, burst)]
                c[0] += first["price"] == max(x["price"], y["price"])
                c[1] += 1
    r9 = boot_ci(list(g[JD549].values()), rng) if g[JD549] else None
    r10 = boot_ci(list(g[NINE].values()), rng) if g[NINE] else None
    L = ["# Firedancer nodes: pre-registered tests P9, P10 (generated by `python -m itb firedancer`)", "",
         "Runs: " + a.runs, "", "| test | validator | higher fee first [95% CI] | bursts | holds |", "|---|---|---|---|---|"]
    for name, pk, val, ok in (("P9", JD549, r9, lambda v: v[2] < 0.5), ("P10", NINE, r10, lambda v: v[1] > 0.8)):
        holds = "-" if not val or val[0] is None else ("yes" if ok(val) else "**no**")
        L.append("| %s | `%s` | %s | %d | %s |" % (name, pk[:8], fmt(val), len(g[pk]), holds))
    out = pathlib.Path("reports") / "firedancer"
    out.mkdir(parents=True, exist_ok=True)
    (out / "summary.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L))
