"""Pre-registered tests for the confirmation runs (see PREREGISTRATION.md). Written and pushed before those runs.

Every burst of a split series has group A (the 4 cheapest probes, sent first) and group B (the 4 dearest, sent
split_gap ms later). Pairs of probes that landed in the same block inside the target's window are of two kinds:
  within  - both from one group: does the higher price sit earlier?            (fee inside a batch)
  across  - one from A, one from B: does the A probe (cheaper, sent first) sit earlier?  (arrival across batches)
Validators are classed by where their TPU points at run start: "front_end" (another host than gossip) or "own_tpu".
"""
import collections
import json
import pathlib
import random

from .analyze import boot_ci, fmt, load_jsonl

FD_9EGR = "9eGrDohdNTAo61DRHyfMuqKWXqYnA3i254Wiszxe8FoY"


def main(cfg, a):
    data = pathlib.Path(cfg.data_dir)
    rng = random.Random(11)
    sends, landed, cls = [], {}, {}
    for d in sorted((data / "runs").glob("*_live")):
        if a.runs and d.name not in a.runs.split(","):
            continue
        rows = load_jsonl(d / "sends.jsonl")
        if not any(r["series"].startswith("split") for r in rows):
            continue
        meta = json.loads((d / "meta.json").read_text())
        for pk, t in meta["targets"].items():
            cls[pk] = "front_end" if t["tpu_elsewhere"] else "own_tpu"
        sends += [r for r in rows if r["series"].startswith("split")]
        for r in load_jsonl(d / "landed.jsonl"):
            if r.get("index") is not None:
                landed[r["sig"]] = r
    if not sends:
        raise SystemExit("no split-series runs found")
    blocks = collections.defaultdict(list)
    for s in sends:
        x = landed.get(s["sig"])
        if x and x.get("in_window"):
            blocks[(s["run"], s["burst"], x["landed_slot"])].append(dict(s, index=x["index"]))
    # (class, kind, gap) -> burst -> [hits, n]
    g = collections.defaultdict(lambda: collections.defaultdict(lambda: [0, 0]))
    for (run, burst, slot), lst in blocks.items():
        for i in range(len(lst)):
            for j in range(i + 1, len(lst)):
                x, y = lst[i], lst[j]
                first = x if x["index"] < y["index"] else y
                gap = x["series"][5:]
                keys = [cls[x["leader"]], x["client"]] + (["fd_9eGr"] if x["leader"] == FD_9EGR else [])
                if x["group"] == y["group"]:
                    hit = first["price"] == max(x["price"], y["price"])
                    kind = "within"
                else:
                    hit = first["group"] == "A"
                    kind = "across"
                for c in keys:
                    for gg in (gap, "all"):
                        cnt = g[(c, kind, gg)][(run, burst)]
                        cnt[0] += hit
                        cnt[1] += 1
    res = {k: boot_ci(list(v.values()), rng) for k, v in g.items()}

    def diff_ci(c, kind, g1, g0):
        """Bootstrap CI of share(g1) - share(g0), resampling bursts within each gap."""
        a1, a0 = list(g[(c, kind, g1)].values()), list(g[(c, kind, g0)].values())
        if not a1 or not a0:
            return None
        share = lambda grp: sum(h for h, n in grp) / max(1, sum(n for h, n in grp))
        stats = sorted(share([a1[rng.randrange(len(a1))] for _ in a1]) - share([a0[rng.randrange(len(a0))] for _ in a0])
                       for _ in range(2000))
        return share(a1) - share(a0), stats[50], stats[1949]

    def r(k):
        return res.get(k)

    tests = [
        ("P1", "front_end: within-group pairs, higher price earlier (both gaps)", r(("front_end", "within", "all")),
         lambda x: x[1] > 0.5),
        ("P2", "front_end: across-group pairs at 120 ms, group A earlier", r(("front_end", "across", "120")),
         lambda x: x[1] > 0.5),
        ("P3", "front_end: across-group share A earlier, 120 ms minus 0 ms",
         diff_ci("front_end", "across", "120", "0"), lambda x: x[1] > 0),
        ("P4", "own_tpu: within-group pairs, higher price earlier (both gaps)", r(("own_tpu", "within", "all")),
         lambda x: x[1] <= 0.5 <= x[2]),
        ("P5", "own_tpu: across-group pairs at 120 ms, group A earlier", r(("own_tpu", "across", "120")),
         lambda x: x[1] > 0.5),
        ("P6", "Firedancer 9eGr: within-group pairs, higher price earlier", r(("fd_9eGr", "within", "all")),
         lambda x: x[1] > 0.6),
    ]
    L = ["# Confirmation runs: pre-registered tests (generated by `python -m itb confirm`)", "",
         "Runs: " + ", ".join(sorted({s["run"] for s in sends})), "",
         "| test | what | result [95% CI] | prediction holds |", "|---|---|---|---|"]
    for name, what, val, ok in tests:
        if val is None or val[0] is None:
            L.append("| %s | %s | no data | - |" % (name, what))
            continue
        shown = ("%+.2f [%+.2f, %+.2f]" % val[:3]) if name == "P3" else fmt(val)
        L.append("| %s | %s | %s | %s |" % (name, what, shown, "yes" if ok(val) else "**no**"))
    L += ["", "## All cells", "", "| group | pairs | gap ms | share [95% CI] |", "|---|---|---|---|"]
    for k in sorted(res):
        L.append("| %s | %s | %s | %s |" % (k[0], k[1], k[2], fmt(res[k])))
    out = pathlib.Path("reports") / "confirmation"
    out.mkdir(parents=True, exist_ok=True)
    (out / "summary.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L))
